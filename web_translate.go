var (
	googleGTXURL       = "https://translate.googleapis.com/translate_a/single"
	googleGTXURLAlt    = "https://translate.google.com/translate_a/single"
	bingTokenURL       = "https://www.bing.com/translator"
	bingTranslateURL   = "https://www.bing.com/ttranslatev3"
	browserAgent       = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36"
	webClient          = &http.Client{Timeout: 18 * time.Second}
	preferWindowsProxy atomic.Bool
	bingTokenCache     = struct {
		sync.Mutex
		key, token, ig, iid, cookie string
		expires                     time.Time
		count                       uint64
	}{}
)

type webResponse struct {
	Status int
	Body   []byte
	Header http.Header
}
type webRequest func(ctx context.Context, method, endpoint string, headers map[string]string, body []byte) (webResponse, error)

var webRequester webRequest = httpWebRequest

func httpWebRequest(ctx context.Context, method, endpoint string, headers map[string]string, body []byte) (webResponse, error) {
	req, err := http.NewRequestWithContext(ctx, method, endpoint, bytes.NewReader(body))
	if err != nil {
		return webResponse{}, err
	}
	req.Header.Set("User-Agent", browserAgent)
	req.Header.Set("Accept", "application/json,text/plain,*/*")
	for k, v := range headers {
		req.Header.Set(k, v)
	}
	// Once the current workstation has succeeded through the Windows proxy,
	// prefer that route for later requests rather than losing time on direct DNS.
	if preferWindowsProxy.Load() {
		res, e := windowsProxyWebRequest(ctx, method, endpoint, headers, body)
		if e == nil {
			return res, nil
		}
		preferWindowsProxy.Store(false)
	}
	// Attempt the direct route briefly before using Windows proxy settings.
	directCtx, cancel := context.WithTimeout(ctx, 12*time.Second)
	defer cancel()
	req = req.WithContext(directCtx)
	r, err := webClient.Do(req)
	if err != nil {
		// Corporate workstations may use WinINET proxy which Go doesn't inherit.
		if ctx.Err() != nil {
			return webResponse{}, ctx.Err()
		}
		res, pe := windowsProxyWebRequest(ctx, method, endpoint, headers, body)
		if pe == nil {
			preferWindowsProxy.Store(true)
		}
		return res, pe
	}
	defer r.Body.Close()
	// On managed Windows PCs, an HTTP 403/407 may be generated by a gateway
	// even while the user's WinINET proxy can access the same service.
	if r.StatusCode == http.StatusForbidden || r.StatusCode == http.StatusProxyAuthRequired {
		proxied, proxyErr := windowsProxyWebRequest(ctx, method, endpoint, headers, body)
		if proxyErr == nil && proxied.Status == http.StatusOK {
			preferWindowsProxy.Store(true)
			return proxied, nil
		}
	}
	b, e := io.ReadAll(io.LimitReader(r.Body, 256*1024))
	if e != nil {
		return webResponse{}, e
	}
	return webResponse{r.StatusCode, b, r.Header}, nil
}

func cleanTranslation(s string) (string, error) {
	s = strings.TrimSpace(s)
	if s == "" {
		return "", errors.New("Translation server returned an empty response")
	}
	return s, nil
}

func parseGoogleResponse(raw []byte) (string, error) {
	// The original extension uses dj=1, then joins sentences[].trans with "",
	// respecting sentence whitespace from the service.
	var response struct {
		Sentences []struct {
			Trans string `json:"trans"`
		} `json:"sentences"`
	}
	if e := json.Unmarshal(raw, &response); e == nil && len(response.Sentences) > 0 {
		var b strings.Builder
		for _, p := range response.Sentences {
			b.WriteString(p.Trans)
		}
		return cleanTranslation(strings.ReplaceAll(b.String(), "\n ", "\n"))
	}
	// Compatible legacy array format (Google sometimes returns this on old routes).
	var arr []json.RawMessage
	if e := json.Unmarshal(raw, &arr); e != nil || len(arr) == 0 {
		return "", errors.New("Unexpected Google response format")
	}
	var pieces [][]json.RawMessage
	if e := json.Unmarshal(arr[0], &pieces); e != nil {
		return "", errors.New("Could not parse Google array response")
	}
	var b strings.Builder
	for _, p := range pieces {
		if len(p) > 0 {
			var t string
			if json.Unmarshal(p[0], &t) == nil {
				b.WriteString(t)
			}
		}
	}
	return cleanTranslation(b.String())
}

func googleTranslate(ctx context.Context, input string) (string, error) {
	q := url.Values{"client": {"gtx"}, "q": {input}, "sl": {"en"}, "tl": {"ko"}, "dj": {"1"}, "hl": {"ko"}, "dt": {"rm", "bd", "t"}}
	headers := map[string]string{"Accept-Language": "ko-KR,ko;q=0.9,en;q=0.8"}
	endpoints := []string{googleGTXURL, googleGTXURLAlt}
	var errs []string
	for _, base := range endpoints {
		target := base + "?" + q.Encode()
		r, e := webRequester(ctx, "GET", target, headers, nil)
		if e != nil {
			errs = append(errs, fmt.Sprintf("%s connection error: %v", base, e))
			continue
		}
		if r.Status != 200 {
			errs = append(errs, fmt.Sprintf("%s HTTP %d", base, r.Status))
			continue
		}
		t, e := parseGoogleResponse(r.Body)
		if e != nil {
			errs = append(errs, fmt.Sprintf("%s response error: %v", base, e))
			continue
		}
		return t, nil
	}
	return "", fmt.Errorf(strings.Join(errs, " / "))
}

var (
	reIG    = regexp.MustCompile(`IG:"([^"]+)"`)
	reIID   = regexp.MustCompile(`data-iid="([^"]+)"`)
	reAbuse = regexp.MustCompile(`params_AbusePreventionHelper\s?=\s?(\[[^\]]+\])`)
)

type bingCred struct {
	Key, Token, IG, IID, Cookie string
	Count                       uint64
}

func parseBingCred(html []byte) (bingCred, error) {
	s := string(html)
	ig := reIG.FindStringSubmatch(s)
	iid := reIID.FindStringSubmatch(s)
	match := reAbuse.FindStringSubmatch(s)
	if len(ig) < 2 || len(iid) < 2 || len(match) < 2 {
		return bingCred{}, errors.New("Could not find a temporary token on the Bing page")
	}
	var fields []json.RawMessage
	if err := json.Unmarshal([]byte(match[1]), &fields); err != nil || len(fields) < 2 {
		return bingCred{}, errors.New("Failed to parse Bing temporary token")
	}
	var key json.Number
	var token string
	if err := json.Unmarshal(fields[0], &key); err != nil {
		return bingCred{}, errors.New("Failed to parse Bing key number")
	}
	if err := json.Unmarshal(fields[1], &token); err != nil {
		return bingCred{}, errors.New("Failed to parse Bing token string")
	}
	return bingCred{Key: key.String(), Token: token, IG: ig[1], IID: iid[1]}, nil
}
func bingCredentials(ctx context.Context) (bingCred, error) {
	bingTokenCache.Lock()
	defer bingTokenCache.Unlock()
	if time.Now().Before(bingTokenCache.expires) && bingTokenCache.token != "" {
		bingTokenCache.count++
		return bingCred{bingTokenCache.key, bingTokenCache.token, bingTokenCache.ig, bingTokenCache.iid, bingTokenCache.cookie, bingTokenCache.count}, nil
	}
	r, e := webRequester(ctx, "GET", bingTokenURL, map[string]string{"Accept": "text/html,application/xhtml+xml,*/*"}, nil)
	if e != nil {
		return bingCred{}, fmt.Errorf("Failed to load Bing token page: %w", e)
	}
	if r.Status != 200 {
		return bingCred{}, fmt.Errorf("Bing token page HTTP %d", r.Status)
	}
	cred, e := parseBingCred(r.Body)
	if e != nil {
		return bingCred{}, e
	}
	if r.Header != nil {
		for _, c := range r.Header.Values("Set-Cookie") {
			p := strings.SplitN(c, ";", 2)
			if p[0] != "" {
				if cred.Cookie != "" {
					cred.Cookie += "; "
				}
				cred.Cookie += p[0]
			}
		}
	}
	interval := time.Hour
	// The site gives an expiry interval as the third field, in milliseconds.
	if match := reAbuse.FindStringSubmatch(string(r.Body)); len(match) > 1 {
		var v []json.RawMessage
		if json.Unmarshal([]byte(match[1]), &v) == nil && len(v) > 2 {
			var ms int64
			if json.Unmarshal(v[2], &ms) == nil && ms > 0 {
				interval = time.Duration(ms) * time.Millisecond
			}
		}
	}
	if interval > time.Hour {
		interval = time.Hour
	}
	if interval < time.Minute {
		interval = time.Minute
	}
	bingTokenCache.key = cred.Key
	bingTokenCache.token = cred.Token
	bingTokenCache.ig = cred.IG
	bingTokenCache.iid = cred.IID
	bingTokenCache.cookie = cred.Cookie
	bingTokenCache.expires = time.Now().Add(interval - 20*time.Second)
	bingTokenCache.count = 1
	cred.Count = 1
	return cred, nil
}
func parseBingResponse(raw []byte) (string, error) {
	var responses []struct {
		Translations []struct {
			Text string `json:"text"`
		} `json:"translations"`
	}
	if err := json.Unmarshal(raw, &responses); err != nil {
		return "", fmt.Errorf("Invalid Bing JSON: %w", err)
	}
	if len(responses) == 0 || len(responses[0].Translations) == 0 {
		return "", errors.New("Bing response contained no translated text")
	}
	return cleanTranslation(responses[0].Translations[0].Text)
}
func bingTranslate(ctx context.Context, input string) (string, error) {
	cred, err := bingCredentials(ctx)
	if err != nil {
		return "", err
	}
	form := url.Values{"text": {input}, "fromLang": {"en"}, "to": {"ko"}, "token": {cred.Token}, "key": {cred.Key}}
	urlParam := url.Values{"IG": {cred.IG}, "IID": {cred.IID + "." + strconv.FormatUint(cred.Count, 10)}, "isVertical": {"1"}}
	h := map[string]string{"Content-Type": "application/x-www-form-urlencoded; charset=UTF-8", "Referer": bingTokenURL, "Accept": "application/json"}
	if cred.Cookie != "" {
		h["Cookie"] = cred.Cookie
	}
	res, e := webRequester(ctx, "POST", bingTranslateURL+"?"+urlParam.Encode(), h, []byte(form.Encode()))
	if e != nil {
		return "", fmt.Errorf("Bing request failed: %w", e)
	}
	if res.Status != 200 {
		return "", fmt.Errorf("Bing HTTP %d", res.Status)
	}
	t, e := parseBingResponse(res.Body)
	if e != nil {
		return "", e
	}
	return t, nil
}

func translateWebFallback(ctx context.Context, text string) (string, string, error) {
	if strings.TrimSpace(text) == "" {
		return "", "", errors.New("Selected English text is empty")
	}
	if len([]byte(text)) > 12000 {
		return "", "", errors.New("Selected text is too long (maximum 12,000 bytes)")
	}
	gctx, cancel := context.WithTimeout(ctx, 12*time.Second)
	defer cancel()
	result, gerr := googleTranslate(gctx, text)
	if gerr == nil {
		return result, "Google", nil
	}
	return "", "", fmt.Errorf("Google translation failed: %v", gerr)
}
func translateWeb(ctx context.Context, text string) (string, error) {
	r, _, e := translateWebFallback(ctx, text)
	return r, e
}
